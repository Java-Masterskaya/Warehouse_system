-- Описание: Делаем barcode NOT NULL, когда весь код уже пишет его
--           и все исторические строки заполнены.
-- ВНИМАНИЕ: Перед деплоем проверить:
--   1. Каждый инстанс приложения работает на новом коде, который пишет barcode.
--   2. SELECT COUNT(*) FROM items WHERE barcode IS NULL; возвращает 0.
--   3. Бэкфилл успешно завершён.
-- Безопасность: Навешивание NOT NULL быстрое, когда NULL-ов нет, но всё равно
--               кратковременно берёт ACCESS EXCLUSIVE. На огромных таблицах
--               запускать в окно низкой нагрузки.
-- ============================================================================

ALTER TABLE items ALTER COLUMN barcode SET NOT NULL;
