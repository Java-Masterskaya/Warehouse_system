-- ============================================================================
-- Шаг 2: Заполнение (Backfill)
-- ============================================================================
-- Описание: Заполняем barcode для существующих строк, где он NULL.
-- ВАЖНАЯ ПРОДАКШЕН-ЗАМЕТКА:
--   Эта миграция БЕЗОПАСНА ТОЛЬКО если в таблице items < 100 000 строк.
--   Для больших таблиц ПРОПУСТИТЕ эту миграцию и используйте Java-backfill
--   (ItemBarcodeBackfillJob), чтобы избежать долгих UPDATE, которые
--   удерживают row-level блокировки и раздувают таблицу (bloat).
--   Если эта миграция пропущена на проде, убедитесь, что ВСЕ NULL заполнены
--   батчевой джобой ДО запуска V21.
-- ============================================================================

UPDATE items
SET barcode = CONCAT('ITEM-', LPAD(id::text, 10, '0'))
WHERE barcode IS NULL;
